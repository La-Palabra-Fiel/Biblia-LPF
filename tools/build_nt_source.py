#!/usr/bin/env python3
"""Build the deterministic TR1894 + Robinson reconciliation ledger."""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools" / "pipeline"))

from books import NT  # noqa: E402
from nt_source import (  # noqa: E402
    ADJUDICATIONS_PATH,
    RECONCILIATION_POLICY,
    ROBINSON_COMMIT,
    ROBINSON_ROOT,
    SCRIVENER_COMMIT,
    SCRIVENER_ROOT,
    TOKENIZATION_POLICY,
    TR_CODE_BY_STEM,
    TR_ROOT,
    apply_adjudication,
    load_robinson_book,
    load_scrivener_book,
    load_boundary_adjudications,
    reconcile_boundary_group,
    reconcile_verse,
    sha256,
)

LEDGER_PATH = TR_ROOT / "tr1894-robinson-reconciliation.json"
MANIFEST_PATH = TR_ROOT / "MANIFEST.json"
REVIEW_PATH = TR_ROOT / "REVIEW.md"


def dump(path: Path, value: dict) -> None:
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def write_review(entries: list[dict], summary: dict) -> None:
    lines = [
        "# TR1894 + Robinson source review",
        "",
        "Generated by `python3 tools/build_nt_source.py`. Do not mark a row",
        "exact merely because it appears here. `REVIEW` requires a documented",
        "human acceptance; `HOLD` requires a documented source decision.",
        "",
        "## Summary",
        "",
        f"- Exact verses: {summary['exactVerses']}",
        f"- Human-approved unique variant paths: {summary['humanApprovedVariantPathVerses']}",
        f"- Human-approved SCV surfaces: {summary['humanApprovedScvSurfaceVerses']}",
        f"- Human-approved SCV verse boundaries: {summary['humanApprovedVerseBoundaryVerses']}",
        f"- Policy-resolved SCV subsequences: {summary['policyScvSubsequenceVerses']}",
        f"- Human-approved morphology paths: {summary['humanApprovedMorphologyPathVerses']}",
        f"- Human-approved morphology merges: {summary['humanApprovedMorphologyMergeVerses']}",
        f"- Unique variant paths awaiting review: {summary['reviewVariantPathVerses']}",
        f"- Unresolved holds: {summary['holdVerses']}",
        "",
        "## Unique UTR variant paths awaiting human review",
        "",
        "| Reference | Proposed omission from UTR variant stream |",
        "| --- | --- |",
    ]
    for entry in entries:
        if entry["status"] != "review-variant-path":
            continue
        omitted = ", ".join(
            f"{token['ordinal']}:{token['surfaceBeta']}{{{token['rawTag']}}}"
            for token in entry["omittedRobinsonTokens"]
        )
        lines.append(f"| {entry['reference']} | `{omitted}` |")
    lines.extend([
        "",
        "## One-to-one surface differences",
        "",
        "These rows have the same token count but different SCV and UTR forms.",
        "They remain `HOLD` until a human chooses the Scrivener surface and",
        "confirms whether the Robinson morphology binds to it.",
        "",
        "| Reference | SCV → UTR |",
        "| --- | --- |",
    ])
    for entry in entries:
        if entry["status"] != "hold" or not entry.get("pairedDifferences"):
            continue
        differences = ", ".join(
            f"{row['ordinal']}:{row['scrivenerBeta']}→{row['robinsonBeta']}"
            for row in entry["pairedDifferences"]
        )
        lines.append(f"| {entry['reference']} | `{differences}` |")
    lines.extend([
        "",
        "## Token-count and sequence differences",
        "",
        "| Reference | SCV tokens | UTR tokens |",
        "| --- | ---: | ---: |",
    ])
    for entry in entries:
        if entry["status"] != "hold" or entry.get("pairedDifferences"):
            continue
        lines.append(
            f"| {entry['reference']} | {len(entry['scrivenerTokens'])} | "
            f"{len(entry['robinsonTokens'])} |"
        )
    REVIEW_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    entries: list[dict] = []
    morphology_files = []
    check_files = []
    exact = approved = approved_scv = approved_boundary = policy_subsequence = approved_morphology = approved_merge = review = hold = tr_token_count = bound_morph_count = 0

    for book in NT:
        path = book.utr_path
        morphology_files.append({
            "path": str(path.relative_to(ROOT)),
            "sha256": sha256(path),
        })
        robinson = load_robinson_book(book)
        scrivener_path = SCRIVENER_ROOT / f"{book.utr_stem}.SCV"
        check_files.append({
            "path": str(scrivener_path.relative_to(ROOT)),
            "sha256": sha256(scrivener_path),
        })
        scrivener = load_scrivener_book(book)
        book_refs = sorted(robinson, key=lambda ref: tuple(int(part) for part in ref.split(".")[1:]))
        if set(book_refs) != set(scrivener):
            missing = sorted(set(book_refs) - set(scrivener))
            extra = sorted(set(scrivener) - set(book_refs))
            raise ValueError(f"{book.slug}: verse inventory differs; missing={missing}, extra={extra}")
        for reference in book_refs:
            boundary = load_boundary_adjudications().get(reference)
            result = (
                reconcile_boundary_group(book, boundary)[reference]
                if boundary is not None
                else apply_adjudication(
                    reconcile_verse(reference, scrivener[reference], robinson[reference])
                )
            )
            tr_token_count += len(result["trTokens"])
            if result["status"] == "exact":
                exact += 1
                bound_morph_count += len(result["trTokens"])
                entries.append({
                    "reference": reference,
                    "status": "exact",
                    "tokenCount": len(result["trTokens"]),
                    "mapping": "ordinal-one-to-one",
                })
            elif result["status"] == "human-approved-variant-path":
                approved += 1
                bound_morph_count += len(result["trTokens"])
                entries.append({
                    "reference": reference,
                    "status": result["status"],
                    "tokenCount": len(result["trTokens"]),
                    "mapping": "human-approved-unique-variant-path",
                    "selectedRobinsonOrdinals": result["proposedRobinsonOrdinals"],
                    "omittedRobinsonTokens": result["omittedRobinsonTokens"],
                    "adjudication": result["adjudication"],
                })
            elif result["status"] == "human-approved-scv-surface":
                approved_scv += 1
                bound_morph_count += len(result["trTokens"])
                entries.append({
                    "reference": reference,
                    "status": result["status"],
                    "tokenCount": len(result["trTokens"]),
                    "mapping": "human-approved-scv-surface-robinson-morphology",
                    "pairedDifferences": result["pairedDifferences"],
                    "adjudication": result["adjudication"],
                })
            elif result["status"] == "human-approved-verse-boundary":
                approved_boundary += 1
                bound_morph_count += len(result["trTokens"])
                entries.append({
                    "reference": reference,
                    "status": result["status"],
                    "tokenCount": len(result["trTokens"]),
                    "mapping": "human-approved-scv-verse-boundary",
                    "adjudication": result["adjudication"],
                })
            elif result["status"] == "policy-scv-subsequence":
                policy_subsequence += 1
                bound_morph_count += len(result["trTokens"])
                entries.append({
                    "reference": reference,
                    "status": result["status"],
                    "tokenCount": len(result["trTokens"]),
                    "mapping": "scv-authoritative-equivalent-morph-subsequence",
                    "selectedRobinsonOrdinals": result["policySelectedRobinsonOrdinals"],
                })
            elif result["status"] == "human-approved-morphology-path":
                approved_morphology += 1
                bound_morph_count += len(result["trTokens"])
                entries.append({
                    "reference": reference,
                    "status": result["status"],
                    "tokenCount": len(result["trTokens"]),
                    "mapping": "human-approved-scv-morphology-path",
                    "selectedRobinsonOrdinals": result["adjudication"]["selectedRobinsonOrdinals"],
                    "adjudication": result["adjudication"],
                })
            elif result["status"] == "human-approved-morphology-merge":
                approved_merge += 1
                bound_morph_count += len(result["trTokens"])
                entries.append({
                    "reference": reference,
                    "status": result["status"],
                    "tokenCount": len(result["trTokens"]),
                    "mapping": "human-approved-scv-token-merge",
                    "adjudication": result["adjudication"],
                })
            elif result["status"] == "review-variant-path":
                review += 1
                entries.append(result)
            else:
                hold += 1
                entries.append(result)

    ledger = {
        "schema": "tr1894-robinson-reconciliation-v1",
        "textAuthority": "Scrivener TR1894",
        "morphologyProvider": "Robinson",
        "tokenizationPolicy": TOKENIZATION_POLICY,
        "reconciliationPolicy": RECONCILIATION_POLICY,
        "summary": {
            "verses": len(entries),
            "exactVerses": exact,
            "humanApprovedVariantPathVerses": approved,
            "humanApprovedScvSurfaceVerses": approved_scv,
            "humanApprovedVerseBoundaryVerses": approved_boundary,
            "policyScvSubsequenceVerses": policy_subsequence,
            "humanApprovedMorphologyPathVerses": approved_morphology,
            "humanApprovedMorphologyMergeVerses": approved_merge,
            "reviewVariantPathVerses": review,
            "holdVerses": hold,
            "trTokens": tr_token_count,
            "tokensWithBoundMorphology": bound_morph_count,
        },
        "verses": entries,
    }
    dump(LEDGER_PATH, ledger)
    write_review(entries, ledger["summary"])

    manifest = {
        "schema": "tr1894-robinson-source-manifest-v1",
        "generator": {
            "version": 1,
            "command": "python3 tools/build_nt_source.py",
            "path": "tools/build_nt_source.py",
            "sha256": sha256(Path(__file__)),
        },
        "text": {
            "authority": "Scrivener TR1894",
            "workingFormat": "Robinson UTR beta-code surface",
            "verseCount": len(entries),
            "tokenizationPolicy": TOKENIZATION_POLICY,
        },
        "morphology": {
            "provider": "Robinson",
            "upstream": "https://github.com/byztxt/greektext-textus-receptus",
            "revision": ROBINSON_COMMIT,
            "license": "Public Domain",
            "files": morphology_files,
        },
        "textVerification": {
            "source": "Scrivener 1894 text-only distribution",
            "upstream": "https://github.com/byztxt/greektext-scrivener",
            "revision": SCRIVENER_COMMIT,
            "license": "Public Domain",
            "files": check_files,
        },
        "reconciliation": {
            "path": str(LEDGER_PATH.relative_to(ROOT)),
            "sha256": sha256(LEDGER_PATH),
            "policy": RECONCILIATION_POLICY,
            **ledger["summary"],
        },
        "humanReviewQueue": {
            "path": str(REVIEW_PATH.relative_to(ROOT)),
            "sha256": sha256(REVIEW_PATH),
        },
        "humanAdjudications": {
            "path": str(ADJUDICATIONS_PATH.relative_to(ROOT)),
            "sha256": sha256(ADJUDICATIONS_PATH),
        },
    }
    dump(MANIFEST_PATH, manifest)
    print(
        f"TR1894 + Robinson: {len(entries)} verses; "
        f"{exact} exact; {approved} VARIANT-APPROVED; {approved_scv} SCV-APPROVED; "
        f"{approved_boundary} BOUNDARY-APPROVED; "
        f"{policy_subsequence} POLICY-SUBSEQUENCE; "
        f"{approved_morphology} MORPH-APPROVED; "
        f"{approved_merge} MERGE-APPROVED; "
        f"{review} REVIEW; {hold} HOLD; "
        f"{bound_morph_count}/{tr_token_count} tokens bound"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

